from bloomerp.models.communication.voip import PhoneCall

from .telnyx_fixtures import TelnyxFixtures


class TestTelnyxCallStatusView(TelnyxFixtures, BloomerpViewTestCase):
    """Keep Telnyx callback replay and state ordering within the shared history models."""

    view_name = "voip_call_status"

    def completed(self, scenario: RequestScenario) -> None:
        """Seed the root created by routing and sign a terminal status update."""
        self.prepare_telnyx()
        self.call = PhoneCall.objects.create(
            **{
                **self.call_args(),
                "provider_call_id": "v3:incoming",
                "direction": "inbound",
                "status": "ringing",
            }
        )
        self.sign(
            scenario,
            {**self.incoming_data(), "CallStatus": "completed", "CallDuration": "12"},
        )

    def duplicate(self, scenario: RequestScenario) -> None:
        """Apply the signed status before delivering its retry."""
        self.completed(scenario)
        response = self.client.post(
            self.get_endpoint(self.view_name, scenario.view_kwargs),
            scenario.data,
            content_type=scenario.content_type,
            headers=scenario.headers,
        )
        self.assertEqual(response.status_code, 200)

    def late(self, scenario: RequestScenario) -> None:
        """Follow completion with a delayed ringing event."""
        self.duplicate(scenario)
        self.sign(scenario, {**self.incoming_data(), "SequenceNumber": "2"})

    def outcome(self, response: HttpResponse) -> bool:
        """Keep terminal state and duration when callbacks repeat or arrive late."""
        self.call.refresh_from_db()
        return self.call.status == "completed" and self.call.duration == 12

    def get_test_scenarios(self) -> list[RequestScenario]:
        """Exercise the real provider dispatch and common reconciliation path."""
        return [
            RequestScenario(
                name="Telnyx completion",
                method="POST",
                prepare=self.completed,
                expected=ExpectedResult(response_validators=self.outcome),
            ),
            RequestScenario(
                name="Telnyx replay",
                method="POST",
                prepare=self.duplicate,
                expected=ExpectedResult(response_validators=self.outcome),
            ),
            RequestScenario(
                name="Late ringing cannot reopen",
                method="POST",
                prepare=self.late,
                expected=ExpectedResult(response_validators=self.outcome),
            ),
        ]
